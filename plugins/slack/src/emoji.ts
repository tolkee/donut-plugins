export const SKIN_TONES: Record<string, string> = {
  "skin-tone-2": "🏻",
  "skin-tone-3": "🏼",
  "skin-tone-4": "🏽",
  "skin-tone-5": "🏾",
  "skin-tone-6": "🏿",
};

export type EmojiLookup = { unicode: string } | { image: string } | null;

export function lookupEmoji(name: string, custom: Record<string, string>, skin?: string): EmojiLookup {
  let current = name;
  for (let hops = 0; hops < 5; hops++) {
    const builtin = EMOJI[current];
    if (builtin) return { unicode: skin && SKIN_TONES[skin] ? builtin + SKIN_TONES[skin] : builtin };
    const value = custom[current];
    if (!value) return null;
    if (!value.startsWith("alias:")) return { image: value };
    current = value.slice("alias:".length);
  }
  return null;
}
